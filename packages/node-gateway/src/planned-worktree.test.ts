import { test } from 'node:test';
import assert from 'node:assert/strict';
import { execFileSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import { mkdtemp, mkdir, writeFile, readFile, symlink, rm, unlink, rename, cp, access } from 'node:fs/promises';
import { join } from 'node:path';
import { createGitWorkspace } from './git-workspace.ts';

const run = (cwd: string, ...args: string[]) => execFileSync('git', args, { cwd, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim();
test('planned worktrees: exact local commits, detached and linked source, ownership and conflicts', async (t) => {
  const root = await mkdtemp('/tmp/opencode/planned-worktree-');
  t.after(() => rm(root, { recursive: true, force: true }));
  const repo = join(root, 'repo'), groups = join(root, 'groups'), managed = join(groups, 'planned-worktrees'), proofs = join(root, 'proofs');
  await mkdir(repo); await mkdir(managed, { recursive: true }); await mkdir(proofs, { mode: 0o700 });
  run(repo, 'init', '-q'); run(repo, 'config', 'user.email', 'test@example.com'); run(repo, 'config', 'user.name', 'Test');
  await writeFile(join(repo, 'file'), 'first'); run(repo, 'add', 'file'); run(repo, 'commit', '-qm', 'first');
  const first = run(repo, 'rev-parse', 'HEAD'); run(repo, 'branch', 'start');
  await writeFile(join(repo, 'file'), 'second'); run(repo, 'commit', '-qam', 'second');
  const second = run(repo, 'rev-parse', 'HEAD');
  run(repo, 'checkout', '-q', '--detach', first);
  await writeFile(join(repo, 'file'), 'dirty');
  const git = createGitWorkspace(async p => p.startsWith(root + '/') ? null : 'outside roots', { groupsDir: groups, plannedProofDir: proofs });
  const inspect = await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null });
  assert.equal(inspect.ok, true); if (!inspect.ok) return;
  assert.equal(inspect.value.oid, first); assert.equal(inspect.value.managedRoot, managed);
  assert.match(inspect.value.identity, /^[0-9a-f]{64}$/);
  const input = { sourcePath: repo, startRef: null, expectedTopLevel: inspect.value.topLevel, expectedCommonDir: inspect.value.commonDir, expectedIdentity: inspect.value.identity, expectedOid: first, targetPath: join(managed, 'a'), branch: 'new-a', operationId: 'op-a' };
  assert.equal((await git.createPlannedWorktree!({ ...input, reconcileOnly: true })).ok, false);
  const created = await git.createPlannedWorktree!(input);
  assert.equal(created.ok, true); if (!created.ok) return;
  assert.equal(created.value.alreadyCreated, false); assert.equal(await readFile(join(input.targetPath, 'file'), 'utf8'), 'first');
  const retry = await git.createPlannedWorktree!(input); assert.equal(retry.ok && retry.value.alreadyCreated, true);
  const reconciled = await git.createPlannedWorktree!({ ...input, reconcileOnly: true }); assert.equal(reconciled.ok && reconciled.value.alreadyCreated, true);
  const opLock = join(proofs, createHash('sha256').update(`operation:${input.operationId}`).digest('hex') + '.lock');
  const repoLock = join(proofs, createHash('sha256').update(`repo:${input.expectedCommonDir}`).digest('hex') + '.lock');
  await writeFile(opLock, 'stale', { mode: 0o600 }); await writeFile(repoLock, 'stale', { mode: 0o600 });
  assert.equal((await git.verifyPlannedWorktree!(input)).ok, true);
  assert.equal((await git.createPlannedWorktree!({ ...input, reconcileOnly: true })).ok, true);
  assert.equal((await git.createPlannedWorktree!(input)).ok, false);
  assert.equal(await readFile(opLock, 'utf8'), 'stale'); assert.equal(await readFile(repoLock, 'utf8'), 'stale');
  await unlink(opLock); await unlink(repoLock);
  assert.equal((await git.verifyPlannedWorktree!(input)).ok, true);
  assert.equal((await git.verifyPlannedWorktree!({ ...input, branch: 'other' })).ok, false);
  run(input.targetPath, 'checkout', '-q', '--detach', second);
  assert.equal((await git.verifyPlannedWorktree!(input)).ok, true);
  assert.equal((await git.createPlannedWorktree!({ ...input, reconcileOnly: true })).ok, false);
  run(input.targetPath, 'checkout', '-q', input.branch);
  const firstProof = join(proofs, createHash('sha256').update(input.operationId).digest('hex') + '.json');
  await rename(firstProof, `${firstProof}.saved`); await symlink(`${firstProof}.saved`, firstProof);
  assert.equal((await git.createPlannedWorktree!({ ...input, reconcileOnly: true })).ok, false);
  assert.equal((await git.verifyPlannedWorktree!(input)).ok, false);
  await unlink(firstProof); await rename(`${firstProof}.saved`, firstProof);
  assert.equal((await git.createPlannedWorktree!({ ...input, targetPath: join(managed, 'b') })).ok, false);
  assert.equal((await git.createPlannedWorktree!({ ...input, operationId: 'op-b' })).ok, false);
  assert.equal((await git.createPlannedWorktree!({ ...input, operationId: 'op-c', targetPath: join(managed, 'c') })).ok, false);
  const linked = await git.inspectPlannedWorktree!({ sourcePath: input.targetPath, startRef: 'refs/heads/start' });
  assert.equal(linked.ok && linked.value.commonDir, inspect.value.commonDir);
  const narrow = createGitWorkspace(async p => p === input.targetPath || p.startsWith(input.targetPath + '/') || p === managed || p.startsWith(managed + '/') ? null : 'outside roots', { groupsDir: groups, plannedProofDir: proofs });
  assert.equal((await narrow.inspectPlannedWorktree!({ sourcePath: input.targetPath, startRef: null })).ok, false);
  run(repo, 'branch', '-f', 'start', 'HEAD~0');
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: 'start' })).ok, false);
  const nested = await git.createPlannedWorktree!({ ...input, targetPath: join(repo, 'nested'), operationId: 'nested', branch: 'nested' }); assert.equal(nested.ok, false);
  await symlink(repo, join(managed, 'link'));
  assert.equal((await git.createPlannedWorktree!({ ...input, targetPath: join(managed, 'link', 'escape'), operationId: 'escape', branch: 'escape' })).ok, false);
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null, expectedOriginUrl: 'https://example.com/x' })).ok, false);
  run(repo, 'remote', 'add', 'origin', 'https://example.com/x.git');
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null, expectedOriginUrl: 'https://example.com/x.git' })).ok, true);
  run(repo, 'remote', 'set-url', '--push', 'origin', 'https://example.com/other.git');
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null, expectedOriginUrl: 'https://example.com/x.git' })).ok, false);
  run(repo, 'remote', 'set-url', '--delete', '--push', 'origin', 'https://example.com/other.git');
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null, expectedOriginUrl: 'https://example.com/other.git' })).ok, false);
  run(repo, 'remote', 'set-url', 'origin', 'git@example.com:team/repo.git');
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null, expectedOriginUrl: 'git@example.com:team/repo.git' })).ok, true);
  run(repo, 'remote', 'set-url', 'origin', `file://${repo}`);
  assert.equal((await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null, expectedOriginUrl: `file://${repo}` })).ok, true);
  const nestedResult = await git.createPlannedWorktree!({ ...input, startRef: 'refs/heads/start', targetPath: join(managed, 'plan', 'repos', 'child'), branch: 'nested-child', operationId: 'op-nested' });
  assert.equal(nestedResult.ok, true);
  // A surviving intent without completion cannot be promoted from matching names.
  const proofPath = join(proofs, createHash('sha256').update('op-nested').digest('hex') + '.json');
  await unlink(proofPath);
  const nestedOpLock = join(proofs, createHash('sha256').update('operation:op-nested').digest('hex') + '.lock');
  await writeFile(nestedOpLock, 'stale', { mode: 0o600 }); await writeFile(repoLock, 'stale', { mode: 0o600 });
  const orphan = await git.createPlannedWorktree!({ ...input, startRef: 'refs/heads/start', targetPath: join(managed, 'plan', 'repos', 'child'), branch: 'nested-child', operationId: 'op-nested', reconcileOnly: true });
  assert.equal(orphan.ok, false);
  assert.equal((await git.verifyPlannedWorktree!({ ...input, startRef: 'refs/heads/start', targetPath: join(managed, 'plan', 'repos', 'child'), branch: 'nested-child', operationId: 'op-nested' })).ok, false);
  await unlink(nestedOpLock); await unlink(repoLock);
  assert.equal((await git.createPlannedWorktree!({ ...input, startRef: 'refs/heads/start', targetPath: join(managed, 'plan', 'repos', 'child'), branch: 'nested-child', operationId: 'op-nested' })).ok, false);
  run(repo, 'branch', '-f', 'start', second);
  const drift = await git.createPlannedWorktree!({ ...input, startRef: 'refs/heads/start', targetPath: join(managed, 'drift'), branch: 'drift', operationId: 'drift' });
  assert.equal(drift.ok, false);
  if (!drift.ok) assert.equal(drift.error.operationSettled, true);
  // A completed checkout stays verifiable when its source HEAD moves.
  run(repo, 'update-ref', 'HEAD', second);
  const afterMove = await git.createPlannedWorktree!({ ...input, reconcileOnly: true });
  assert.equal(afterMove.ok && afterMove.value.alreadyCreated, true);
  run(repo, 'update-ref', 'HEAD', first);

  const config = join(repo, '.git', 'config');
  const validConfig = await readFile(config, 'utf8');
  await writeFile(config, `${validConfig}\n[broken\n`);
  const malformed = await git.createPlannedWorktree!({ ...input, targetPath: join(managed, 'bad-config'), branch: 'bad-config', operationId: 'bad-config' });
  assert.equal(malformed.ok, false);
  await writeFile(config, validConfig);

  // The same path, branch, OID and common-dir do not prove the original incarnation.
  run(repo, 'worktree', 'remove', input.targetPath);
  run(repo, 'worktree', 'add', '--', input.targetPath, input.branch);
  assert.equal(run(input.targetPath, 'rev-parse', 'HEAD'), first);
  const replaced = await git.createPlannedWorktree!({ ...input, reconcileOnly: true });
  assert.equal(replaced.ok, false);
  assert.equal((await git.verifyPlannedWorktree!(input)).ok, false);
  if (!replaced.ok) assert.equal(replaced.error.operationSettled, undefined);
  // Replacing only the common Git directory is detected even with an unchanged top-level directory.
  await rename(join(repo, '.git'), join(root, 'old-git'));
  await cp(join(root, 'old-git'), join(repo, '.git'), { recursive: true });
  const commonReplacement = await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null });
  assert.equal(commonReplacement.ok, true);
  if (commonReplacement.ok) assert.notEqual(commonReplacement.value.identity, input.expectedIdentity);
  assert.equal((await git.createPlannedWorktree!({ ...input, reconcileOnly: true })).ok, false);
  assert.equal((await git.verifyPlannedWorktree!(input)).ok, false);
});

test('planned worktree rejects same-path same-commit repository replacement before first write', async (t) => {
  const root = await mkdtemp('/tmp/opencode/planned-identity-');
  t.after(() => rm(root, { recursive: true, force: true }));
  const repo = join(root, 'repo'), groups = join(root, 'groups'), managed = join(groups, 'planned-worktrees'), proofs = join(root, 'proofs');
  await mkdir(repo); await mkdir(managed, { recursive: true }); await mkdir(proofs, { mode: 0o700 });
  run(repo, 'init', '-q'); run(repo, 'config', 'user.email', 'test@example.com'); run(repo, 'config', 'user.name', 'Test');
  await writeFile(join(repo, 'file'), 'content'); run(repo, 'add', 'file'); run(repo, 'commit', '-qm', 'initial');
  const git = createGitWorkspace(async p => p.startsWith(root + '/') ? null : 'outside roots', { groupsDir: groups, plannedProofDir: proofs });
  const inspection = await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null });
  assert.equal(inspection.ok, true); if (!inspection.ok) return;
  await rename(repo, join(root, 'old-repo')); await cp(join(root, 'old-repo'), repo, { recursive: true });
  const replacement = await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null });
  assert.equal(replacement.ok, true); if (!replacement.ok) return;
  assert.equal(replacement.value.oid, inspection.value.oid);
  assert.notEqual(replacement.value.identity, inspection.value.identity);
  const input = { sourcePath: repo, startRef: null, expectedTopLevel: inspection.value.topLevel, expectedCommonDir: inspection.value.commonDir, expectedIdentity: inspection.value.identity, expectedOid: inspection.value.oid, targetPath: join(managed, 'target'), branch: 'planned', operationId: 'replacement' };
  assert.equal((await git.createPlannedWorktree!(input)).ok, false);
  await assert.rejects(access(input.targetPath));
  await assert.rejects(access(join(proofs, createHash('sha256').update(input.operationId).digest('hex') + '.json.intent')));
  assert.throws(() => run(repo, 'show-ref', '--verify', '--quiet', 'refs/heads/planned'));
  // A different Git directory at the same location is independently detected.
  const current = replacement.value;
  await rename(join(repo, '.git'), join(root, 'old-git')); await cp(join(root, 'old-git'), join(repo, '.git'), { recursive: true });
  const second = await git.inspectPlannedWorktree!({ sourcePath: repo, startRef: null });
  assert.equal(second.ok, true); if (!second.ok) return;
  assert.notEqual(second.value.identity, current.identity);
  assert.equal((await git.createPlannedWorktree!({ ...input, expectedIdentity: current.identity, operationId: 'gitdir-replacement' })).ok, false);
});
